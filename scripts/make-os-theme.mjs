// Scorpion OS's non-web surfaces in Scorpion's theme colours: labwc's window
// frames and menus, the lock screen (swaylock) and the sign-in screen
// (LightDM's GTK greeter), all from one theme in src/renderer/themes.css, so
// they match the rail, the wheel and the app. Run it after changing a theme:
//   node scripts/make-os-theme.mjs [theme]       (default: classic)
//   node scripts/make-os-theme.mjs --check       (exit 1 if a file is stale)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const theme = args.find((a) => !a.startsWith('--')) || 'classic';

// The variables of one theme block in themes.css.
export function themeColors(css, name) {
  const m = new RegExp(`html\\[data-theme="${name}"\\]\\s*\\{([^}]*)\\}`).exec(css);
  if (!m) throw new Error(`No theme "${name}" in themes.css`);
  return Object.fromEntries([...m[1].matchAll(/--([\w-]+):\s*([^;]+);/g)].map(([, k, v]) => [k, v.trim()]));
}
const hex = (c) => { if (!/^#[0-9a-f]{6}$/i.test(c)) throw new Error(`Not a #rrggbb colour: ${c}`); return c.toLowerCase(); };
const bare = (c) => hex(c).slice(1);

export function osThemeFiles(c, name) {
  const head = (comment) => `${comment} Generated by scripts/make-os-theme.mjs from the "${name}" theme in src/renderer/themes.css; change it there.\n`;
  return {
    'os/rootfs/usr/share/themes/Scorpion/labwc/themerc': `${head('#')}border.width: 1
padding.height: 6
window.active.border.color: ${hex(c.border)}
window.inactive.border.color: ${hex(c['panel-2'])}
window.active.title.bg.color: ${hex(c.panel)}
window.inactive.title.bg.color: ${hex(c.bg)}
window.active.label.text.color: ${hex(c.text)}
window.inactive.label.text.color: ${hex(c.muted)}
window.label.text.justify: center
window.active.button.unpressed.image.color: ${hex(c.accent)}
window.inactive.button.unpressed.image.color: ${hex(c.muted)}
window.active.indicator.toggled-keybind.color: ${hex(c.accent)}
menu.items.bg.color: ${hex(c.panel)}
menu.items.text.color: ${hex(c.text)}
menu.items.active.bg.color: ${hex(c.border)}
menu.items.active.text.color: ${hex(c.accent)}
menu.separator.color: ${hex(c['panel-2'])}
osd.bg.color: ${hex(c.panel)}
osd.border.color: ${hex(c.accent)}
osd.label.text.color: ${hex(c.text)}
osd.window-switcher.item.active.border.color: ${hex(c.accent)}
`,
    // swaylock reads /etc/swaylock/config when the user has none of their own.
    'os/rootfs/etc/swaylock/config': `${head('#')}color=${bare(c.bg)}
inside-color=${bare(c.panel)}cc
inside-clear-color=${bare(c.panel)}cc
inside-ver-color=${bare(c.panel)}cc
inside-wrong-color=${bare(c.danger || c.accent)}55
ring-color=${bare(c.accent)}
ring-clear-color=${bare(c.muted)}
ring-ver-color=${bare(c.accent)}
ring-wrong-color=${bare(c.danger || '#e5484d')}
key-hl-color=${bare(c.text)}
bs-hl-color=${bare(c.danger || '#e5484d')}
line-color=00000000
line-clear-color=00000000
line-ver-color=00000000
line-wrong-color=00000000
separator-color=00000000
text-color=${bare(c.text)}
text-clear-color=${bare(c.text)}
text-ver-color=${bare(c.text)}
text-wrong-color=${bare(c.text)}
font=Ubuntu
indicator-radius=90
indicator-thickness=8
show-failed-attempts
ignore-empty-password
`,
    'os/rootfs/etc/lightdm/lightdm-gtk-greeter.conf': `${head('#')}[greeter]
theme-name=Yaru-dark
icon-theme-name=Yaru
cursor-theme-name=Yaru
font-name=Ubuntu 11
background=${hex(c.bg)}
user-background=false
indicators=~host;~spacer;~clock;~spacer;~session;~a11y;~power
clock-format=%a %d %b, %H:%M
`,
  };
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, '/').replace(/^\//, '')}`) {
  const colors = themeColors(fs.readFileSync(path.join(root, 'src/renderer/themes.css'), 'utf8'), theme);
  let stale = 0;
  for (const [rel, text] of Object.entries(osThemeFiles(colors, theme))) {
    const file = path.join(root, rel);
    const now = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
    if (now === text) continue;
    if (check) { console.error(`stale: ${rel}`); stale++; continue; }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`wrote ${rel}`);
  }
  if (stale) process.exit(1);
}
